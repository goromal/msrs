//! Replay-gate helpers: read a unified log back and compare a fresh machine's
//! outputs with the recorded ones.
//!
//! The pieces are deliberately small so a service keeps control of what a
//! "step" is: [`read_copperlists`] decodes the log and says how decoding
//! ended, the service maps each copperlist to a [`Recorded`] input/output
//! pair (which slot is the input, whether an empty slot is a `Tick`), and
//! [`replay_gate`] replays them and reports the first divergence.

use cu29::bincode::{
    config::standard, decode_from_std_read, encode_to_vec, error::DecodeError, Decode, Encode,
};
use cu29::prelude::*;
use std::fmt::Debug;
use std::io::ErrorKind;
use std::path::Path;

/// How the copperlist decode loop ended.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LogEnd {
    /// The stream ended cleanly at a record boundary.
    Eof,
    /// Any other decode error, such as corrupted bytes. A record truncated at
    /// the very end still reads as [`LogEnd::Eof`]; check the expected count.
    Error(String),
}

/// Decode every copperlist of a unified log and report how decoding ended.
///
/// `P` is the `CuMsgs` type generated by `gen_cumsgs!` in the service binary.
pub fn read_copperlists<P>(log_base: &Path) -> CuResult<(Vec<CopperList<P>>, LogEnd)>
where
    P: CopperListTuple,
    CopperList<P>: Decode<()>,
{
    let read = match UnifiedLoggerBuilder::new()
        .file_base_name(log_base)
        .build()
        .map_err(|e| CuError::from(format!("open unified log {}: {e}", log_base.display())))?
    {
        UnifiedLogger::Read(r) => r,
        UnifiedLogger::Write(_) => {
            return Err(CuError::from("expected a read-only unified logger"))
        }
    };
    let mut reader = UnifiedLoggerIOReader::new(read, UnifiedLogType::CopperList);
    let mut copperlists = Vec::new();
    let end = loop {
        match decode_from_std_read::<CopperList<P>, _, _>(&mut reader, standard()) {
            Ok(cl) => copperlists.push(cl),
            Err(DecodeError::UnexpectedEnd { .. }) => break LogEnd::Eof,
            Err(DecodeError::Io { inner, .. }) if inner.kind() == ErrorKind::UnexpectedEof => {
                break LogEnd::Eof
            }
            Err(e) => break LogEnd::Error(format!("{e:?}")),
        }
    };
    Ok((copperlists, end))
}

/// One recorded decision: the copperlist id, its input and its output.
#[derive(Debug, Clone)]
pub struct Recorded<I, O> {
    pub id: u64,
    pub input: I,
    pub output: O,
}

/// Result of [`replay_gate`].
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct GateReport {
    /// Recorded steps replayed.
    pub steps: usize,
    /// Steps whose replayed output differs from the recording.
    pub divergent: usize,
    /// The first divergence: copperlist id, input, recorded and replayed output.
    pub first_divergence: Option<String>,
    /// `(previous, next)` copperlist ids wherever they are not consecutive.
    pub id_gaps: Vec<(u64, u64)>,
}

impl GateReport {
    /// At least one step, no divergence and no id gap.
    pub fn passed(&self) -> bool {
        self.steps > 0 && self.divergent == 0 && self.id_gaps.is_empty()
    }
}

/// Replay `recorded` through `step` (usually a closure over a cold machine
/// calling `run_step`/`run_step_all`) and compare outputs as bincode bytes.
///
/// Bytes rather than `PartialEq`: a float payload holding NaN is never equal
/// to itself, but its encoding is. Every step is replayed even after a
/// divergence, because a divergence can disappear later and a final-state
/// match proves nothing; use `first_divergence` to diagnose.
pub fn replay_gate<I: Debug, O: Encode + Debug>(
    recorded: &[Recorded<I, O>],
    mut step: impl FnMut(&I) -> O,
) -> GateReport {
    let mut report = GateReport {
        steps: recorded.len(),
        ..Default::default()
    };
    let mut prev: Option<u64> = None;
    for r in recorded {
        if let Some(p) = prev {
            if r.id != p + 1 {
                report.id_gaps.push((p, r.id));
            }
        }
        prev = Some(r.id);
        let replayed = step(&r.input);
        let same =
            encode_to_vec(&replayed, standard()).ok() == encode_to_vec(&r.output, standard()).ok();
        if !same {
            report.divergent += 1;
            if report.first_divergence.is_none() {
                report.first_divergence = Some(format!(
                    "copperlist {}:\n  input:    {:?}\n  recorded: {:?}\n  replayed: {:?}",
                    r.id, r.input, r.output, replayed
                ));
            }
        }
    }
    report
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rec(ids: &[u64], outputs: &[f64]) -> Vec<Recorded<u64, f64>> {
        ids.iter()
            .zip(outputs)
            .map(|(&id, &output)| Recorded {
                id,
                input: id,
                output,
            })
            .collect()
    }

    #[test]
    fn passes_identical_outputs_including_nan() {
        let r = rec(&[0, 1, 2], &[1.0, f64::NAN, 3.0]);
        let out = replay_gate(&r, |i| [1.0, f64::NAN, 3.0][*i as usize]);
        assert!(out.passed(), "{out:?}");
    }

    #[test]
    fn reports_first_divergence_and_keeps_counting() {
        let r = rec(&[5, 6, 7], &[1.0, 2.0, 3.0]);
        let out = replay_gate(&r, |i| if *i == 6 || *i == 7 { 0.0 } else { 1.0 });
        assert_eq!(out.divergent, 2);
        assert!(out.first_divergence.unwrap().starts_with("copperlist 6:"));
    }

    #[test]
    fn detects_id_gaps() {
        let r = rec(&[0, 1, 3], &[0.0; 3]);
        let out = replay_gate(&r, |_| 0.0);
        assert_eq!(out.id_gaps, vec![(1, 3)]);
        assert!(!out.passed());
    }

    #[test]
    fn empty_recording_does_not_pass() {
        let out = replay_gate::<u64, f64>(&[], |_| 0.0);
        assert!(!out.passed());
    }
}
